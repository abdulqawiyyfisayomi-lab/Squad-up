create or replace function public.join_squad(p_request_id text, p_data jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  request_row public.squad_requests%rowtype;
  member_total integer;
  capacity integer;
  player_tag text;
begin
  if current_user_id is null then
    raise exception 'Log in to join a squad.';
  end if;

  select * into request_row
  from public.squad_requests
  where id = p_request_id
  for update;

  if not found then
    raise exception 'This squad request is no longer available.';
  end if;
  if request_row.owner_id = current_user_id then
    raise exception 'Hosts cannot join their own squad.';
  end if;
  if request_row.data ->> 'closed' = 'true' then
    raise exception 'This squad is not accepting new players.';
  end if;

  capacity := case
    when request_row.data ->> 'need' ~ '^[0-9]{1,2}$'
      then greatest(1, least(20, (request_row.data ->> 'need')::integer))
    else 1
  end;
  select count(*) into member_total
  from public.squad_members
  where request_id = p_request_id;
  if member_total >= capacity then
    raise exception 'This squad is full.';
  end if;

  select gamer_tag into player_tag
  from public.profiles
  where id = current_user_id;

  insert into public.squad_members (id, request_id, user_id, created_at, data)
  values (
    p_request_id || '_' || current_user_id::text,
    p_request_id,
    current_user_id,
    now(),
    coalesce(p_data, '{}'::jsonb) || jsonb_build_object('name', coalesce(player_tag, 'Player'))
  );
end;
$$;

revoke all on function public.join_squad(text, jsonb) from public, anon;
grant execute on function public.join_squad(text, jsonb) to authenticated;

