create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, gamer_tag)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'gamer_tag'), ''), 'Player'), 20)
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

